// Range of Numbers

/**
 * Function to create an array containing a range of numbers from a to b
 * @param {number} a - The starting number of the range
 * @param {number} b - The ending number of the range
 */

export function buatRentang(a, b){
    let rentang = [];
    let row = '';

    for(let i=a; i<=b; i++){
        rentang.push(i);
    }
    console.log(rentang);

    return row
}

